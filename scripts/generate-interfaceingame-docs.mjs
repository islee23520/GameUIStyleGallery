#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "game-ui/interfaceingame/data");
const check = process.argv.includes("--check");
const readJson = (name) => JSON.parse(fs.readFileSync(path.join(dataDir, name), "utf8"));

const games = readJson("games.json");
const screenshots = readJson("screenshots.json");
const taxonomies = readJson("taxonomies.json");
const manifest = readJson("manifest.json");
const gameBySlug = new Map(games.map((game) => [game.slug, game]));

const label = (taxonomy, slug) => taxonomies[taxonomy]?.[slug] ?? slug;
const cell = (value) => String(value).replaceAll("|", "\\|");
const percent = (part, whole) => (whole === 0 ? "0.0" : ((100 * part) / whole).toFixed(1));
const byCountThenSlug = ([a, x], [b, y]) => y - x || a.localeCompare(b);

function frontmatter(title, description) {
  return ["---", "type: Generated Reference", `title: ${title}`, `description: ${description}`, "domain: game-ui", "lifecycle: experimental", "---", ""].join("\n");
}

const sourceNote = `Generated by \`scripts/generate-interfaceingame-docs.mjs\` from [the catalog data](data/manifest.json), retrieved from [Interface In Game](${manifest.source}) on ${manifest.retrieved_on}. Do not edit by hand; rerun the generator after refreshing the data.`;

function catalog() {
  const lines = [
    frontmatter("Interface In Game Game Catalog", "Generated per-game index of the Interface In Game archive with facets and screenshot counts."),
    "# Interface In Game Game Catalog",
    "",
    "Primary role: generated game lookup table.",
    "",
    sourceNote,
    "",
    `The table lists ${games.length} games, ${manifest.counts.images} screenshot images, and ${manifest.counts.videos} video captures. Titles link to the source game page; facet values are site-local labels. Publisher values are source slugs because the source exposes no publisher labels.`,
    "",
    "| Game | Released | Genres | Themes | Platforms | Publishers | Images | Videos |",
    "| --- | --- | --- | --- | --- | --- | ---: | ---: |",
  ];
  for (const game of games) {
    lines.push(
      `| [${cell(game.title)}](${game.url}) | ${game.release_date ?? "unknown"} | ${cell(game.genres.map((s) => label("genres", s)).join(", ") || "-")} | ${cell(game.themes.map((s) => label("themes", s)).join(", ") || "-")} | ${cell(game.platforms.map((s) => label("platforms", s)).join(", ") || "-")} | ${cell(game.publishers.map((s) => `\`${s}\``).join(", ") || "-")} | ${game.screenshot_count} | ${game.video_count} |`,
    );
  }
  lines.push("", "## IA Navigation", "", "Parent: [Interface In Game Catalog](index.md).", "Next: [Genre And Element Matrix](genre-element-matrix.md).", "");
  return lines.join("\n");
}

function matrix() {
  const elements = Object.keys(taxonomies.elements);
  const genres = Object.keys(taxonomies.genres);
  const total = screenshots.length;
  const elementCount = new Map(elements.map((e) => [e, 0]));
  const elementGames = new Map(elements.map((e) => [e, new Set()]));
  const genreItems = new Map(genres.map((g) => [g, 0]));
  const cellCount = new Map();
  const pairCount = new Map();
  for (const shot of screenshots) {
    const shotGenres = gameBySlug.get(shot.game)?.genres ?? [];
    for (const genre of shotGenres) genreItems.set(genre, (genreItems.get(genre) ?? 0) + 1);
    for (const element of shot.elements) {
      elementCount.set(element, (elementCount.get(element) ?? 0) + 1);
      elementGames.get(element)?.add(shot.game);
      for (const genre of shotGenres) cellCount.set(`${element}|${genre}`, (cellCount.get(`${element}|${genre}`) ?? 0) + 1);
      for (const other of shot.elements) if (other !== element) pairCount.set(`${element}|${other}`, (pairCount.get(`${element}|${other}`) ?? 0) + 1);
    }
  }
  const orderedElements = [...elementCount.entries()].sort(byCountThenSlug).map(([e]) => e);
  const lift = (element, genre) => {
    const inElement = cellCount.get(`${element}|${genre}`) ?? 0;
    const elementTotal = elementCount.get(element) || 1;
    const base = (genreItems.get(genre) ?? 0) / total;
    return base === 0 ? 0 : inElement / elementTotal / base;
  };

  const lines = [
    frontmatter("Interface In Game Genre And Element Matrix", "Generated element coverage, co-occurrence, and genre lift computed from the Interface In Game catalog data."),
    "# Interface In Game Genre And Element Matrix",
    "",
    "Primary role: generated coverage matrix.",
    "",
    sourceNote,
    "",
    `Counts are capture items (${total} total: images plus videos). One capture can carry several elements, so element shares do not sum to 100 percent. Genre lift is the element's share of captures from games with that genre divided by that genre's share of all captures; values above 1.0 mean the element is over-represented in that genre. Lift describes this archive's sampling, not the market.`,
    "",
    "## Element Coverage",
    "",
    "| Element | Label | Captures | Share of captures | Games | Top co-occurring elements | Highest genre lift (min. 20 captures) |",
    "| --- | --- | ---: | ---: | ---: | --- | --- |",
  ];
  for (const element of orderedElements) {
    const co = [...pairCount.entries()]
      .filter(([key]) => key.startsWith(`${element}|`))
      .map(([key, count]) => [key.split("|")[1], count])
      .sort(byCountThenSlug)
      .slice(0, 3)
      .map(([other, count]) => `\`${other}\` (${count})`)
      .join(", ");
    const lifts = genres
      .filter((genre) => (cellCount.get(`${element}|${genre}`) ?? 0) >= 20)
      .map((genre) => [genre, lift(element, genre)])
      .sort(([a, x], [b, y]) => y - x || a.localeCompare(b))
      .slice(0, 3)
      .map(([genre, value]) => `${label("genres", genre)} ${value.toFixed(2)}`)
      .join(", ");
    lines.push(`| \`${element}\` | ${label("elements", element)} | ${elementCount.get(element)} | ${percent(elementCount.get(element), total)}% | ${elementGames.get(element).size} | ${co || "-"} | ${lifts || "-"} |`);
  }
  lines.push("", "## Genre By Element Captures", "", `Rows are elements; columns are genres. Each cell counts captures carrying the element from games tagged with the genre.`, "");
  lines.push(`| Element | ${genres.map((g) => label("genres", g)).join(" | ")} |`);
  lines.push(`| --- | ${genres.map(() => "---:").join(" | ")} |`);
  for (const element of orderedElements) {
    lines.push(`| \`${element}\` | ${genres.map((g) => cellCount.get(`${element}|${g}`) ?? 0).join(" | ")} |`);
  }
  lines.push("", "## IA Navigation", "", "Parent: [Interface In Game Catalog](index.md).", "Next: [Interface In Game Element Patterns](elements.md).", "");
  return lines.join("\n");
}

const outputs = {
  "game-ui/interfaceingame/catalog.md": catalog(),
  "game-ui/interfaceingame/genre-element-matrix.md": matrix(),
};

let stale = 0;
for (const [relative, content] of Object.entries(outputs)) {
  const target = path.join(root, relative);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === content) continue;
  if (check) {
    stale += 1;
    process.stderr.write(`${relative}: stale; run node scripts/generate-interfaceingame-docs.mjs\n`);
  } else {
    fs.writeFileSync(target, content);
    process.stdout.write(`wrote ${relative}\n`);
  }
}
process.exitCode = stale ? 1 : 0;
